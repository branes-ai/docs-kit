// The sites' shared theme: dark slate, with the repo's accent.
export function themeCss({ accent: { dark, light } }) {
  return `/* Generated by docs-kit from docs-kit.config.mjs; edit the accent there. */

:root {
  --sl-color-accent-low: ${dark.low};
  --sl-color-accent: ${dark.accent};
  --sl-color-accent-high: ${dark.high};

  --sl-color-bg: #12151b;
  --sl-color-bg-nav: #191d25;
  --sl-color-bg-sidebar: #191d25;
}

/* Light mode keeps the same accent, darkened for contrast. */
:root[data-theme='light'] {
  --sl-color-accent-low: ${light.low};
  --sl-color-accent: ${light.accent};
  --sl-color-accent-high: ${light.high};
  --sl-color-bg: #ffffff;
  --sl-color-bg-nav: #f7f7f8;
  --sl-color-bg-sidebar: #f7f7f8;
}

/* Wide tables scroll inside their own box instead of widening the page at
   phone width. */
.sl-markdown-content table {
  display: block;
  overflow-x: auto;
}
`;
}
